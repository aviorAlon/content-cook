def test_lang_from_headers():
    assert i18n.lang_from_headers({"x-storystudio-lang": "en"}) == "en"
    assert i18n.lang_from_headers({"x-storystudio-lang": "zh", "accept-language": "en-US"}) == "zh"
    assert i18n.lang_from_headers({"accept-language": "en-GB,en;q=0.9"}) == "en"
    assert i18n.lang_from_headers({"accept-language": "zh-CN"}) == "zh"
    assert i18n.lang_from_headers({}) == "zh"


def test_tr_exact_pattern_and_fallback(rules):
    assert i18n.tr("知道了", "en") == "Got it"
    assert i18n.tr("还有 3 镜没有可用首帧", "en") == "3 shots still lack a usable first frame"
    assert i18n.tr("没有规则的句子", "en") == "没有规则的句子"
    assert i18n.tr("知道了", "zh") == "知道了"
    assert i18n.tr(None, "en") is None and i18n.tr(3, "en") == 3
    # 「人话（原文）」：只翻前半段，原文保留
    out = i18n.tr("frame-S1 被服务商拒绝：QuotaExhausted（submission rejected for frame-S1: QuotaExhausted）", "en")
    assert out == "frame-S1 was rejected by the provider: QuotaExhausted (submission rejected for frame-S1: QuotaExhausted)"


def test_tr_obj_translates_only_text_keys(rules):
    data = {
        "next_step": {"key": "frames", "label": "知道了", "hint": "还有 2 镜没有可用首帧"},
        "title": "知道了",                      # 用户内容键：不动
        "warnings": ["知道了", "别的"],
        "status": {"image": ["知道了"], "video": []},
        "items": [{"message": "知道了", "id": "知道了"}],
    }
    i18n.tr_obj(data, i18n.TEXT_KEYS, "en", lists=i18n.LIST_KEYS)
    assert data["next_step"] == {"key": "frames", "label": "Got it", "hint": "2 shots still lack a usable first frame"}
    assert data["title"] == "知道了"
    assert data["warnings"] == ["Got it", "别的"]
    assert data["status"] == {"image": ["Got it"], "video": []}
    assert data["items"] == [{"message": "Got it", "id": "知道了"}]
    same = {"label": "知道了"}
    assert i18n.tr_obj(same, lang="zh") == {"label": "知道了"}


def test_middleware_translates_json_only_for_english(rules, tmp_path, monkeypatch):
    monkeypatch.setenv("STORYSTUDIO_HOME", str(tmp_path / "home"))
    monkeypatch.setenv("STORYSTUDIO_SETTINGS", str(tmp_path / "home" / "settings.json"))
    zh = client.post("/api/episodes/storyvideo/NOPE-1/retry-failed", json={})
    en = client.post("/api/episodes/storyvideo/NOPE-1/retry-failed", json={}, headers={"X-StoryStudio-Lang": "en"})
    assert zh.status_code == en.status_code
    assert zh.json()["detail"] != en.json()["detail"] or "NOPE-1" in zh.json()["detail"]
    # 精确命中的 detail
    monkeypatch.setattr(i18n_rules, "EXACT", {**i18n_rules.EXACT, zh.json()["detail"]: "translated detail"})
    en2 = client.post("/api/episodes/storyvideo/NOPE-1/retry-failed", json={}, headers={"X-StoryStudio-Lang": "en"})
    assert en2.json()["detail"] == "translated detail"
    assert client.post("/api/episodes/storyvideo/NOPE-1/retry-failed", json={}).json()["detail"] == zh.json()["detail"]
    # 非 JSON（首页 HTML）不碰
    assert client.get("/", headers={"X-StoryStudio-Lang": "en"}).status_code == 200


def test_real_rules_compile_and_cover_core_strings():
    """真实规则表：每条正则能编译；几条最常见的文案在英文下不再是中文。"""

    import re

    i18n._compiled = None
    for pat, rep in i18n_rules.PATTERNS:
        re.compile(pat)
    samples = [
        "开始制作", "还有 3 镜没有可用首帧", "余额或配额不足", "内容被审核拦截",
        "服务商账户充值/等配额恢复后，点「重提失败任务」", "没有失败的任务可以重提",
        "生图模型还没配置——去「模型设置」",
        "shot S1: 可读文字「4 days」放在「bottom」，会被交付面的「Bottom band」挡住——挪到安全区或换载体",
        "抖音（竖屏）",
    ]
    han = re.compile(r"[\u4e00-\u9fff]")
    untranslated = [s for s in samples if han.search(i18n.tr(s, "en"))]
    assert not untranslated, untranslated


