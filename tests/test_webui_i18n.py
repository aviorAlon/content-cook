# 静态扫描：src 下所有 raise …Error(…) / HTTPException(…, …) 的中文字面量都要有英文规则。
# 占位符按表达式名代入几种代表值（镜号 / 数字 / 原因），任一形状翻干净即算过；条件表达式两个分支各出一份样本。
# 白名单只放「样本代不出真实形状」的：真实形状由 test_whitelisted_raise_literals_translate_in_real_shape 走真代码生成再验。
_RAISE_WHITELIST = (
    # podcast/spec.py：span 是「N 人」或「N 到 M 人」，_PODCAST_SPEC_ERRORS 里两条规则各有覆盖
    "形式「{label}」要 {span}，现在有 {len(out)} 人",
    # music/use.py：choices 是「intro（片头） / bed（垫乐） / outro（片尾）」，_MUSIC_PODCAST_RULES 里有整句规则
    "播客的 slot 是槽名，只能是 {choices}，收到「{text}」",
    # genkit/router.py：角色标签只会是 视频 / 配乐 / 生图，三条规则各有覆盖
    "但「模型设置」里{_ROLE_LABEL.get(role, role)}来源现在是",
    # podcast/audio.py：槽名只会是 片头 / 垫乐 / 片尾（MUSIC_SLOT_LABELS），两条规则按真实槽名生成
    "音乐文件读不出（{path.name}）",
    # routers/episodes.py：原因来自固定的几条 blockers，每条都有整句规则（另有一条兜底）
    "没有恢复：{blockers[0]}——先把现有的同 id 项目归档或改名",
    # webui/uploads.py：accepted 是格式标签拼的（png / jpg / jpeg / webp 文件、.mp3 / .wav 音频），两条规则各有覆盖
    "只接受 {accepted}，收到的是 {fmt or '未知格式'}",
)
_RAISE_NAMES = ("HTTPException", "TaskBusy")


def _raise_sample(expr: str, numeric: bool) -> str:
    text = expr.lower()
    if numeric:
        return "3"
    if "join(" in text:
        return "S1, S2"
    if any(k in text for k in ("id", "shot", "target", "name", "key", "field", "kind", "label", "role", "path", "file", "model", "who",
                               "value", "suffix", "source", "slot", "prefix", "version")):
        return "S1_A"
    return "abc def"


def _raise_render(node, numeric: bool) -> list[str] | None:
    """字面量 / f-string / 字符串相加 → 样本串列表；不是字面量返回 None。"""

    import ast

    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return [node.value]
    if isinstance(node, ast.JoinedStr):
        variants = [""]
        for part in node.values:
            if isinstance(part, ast.Constant):
                variants = [v + str(part.value) for v in variants]
            elif isinstance(part, ast.FormattedValue):
                inner = part.value
                if isinstance(inner, ast.IfExp):
                    choices = []
                    for branch in (inner.body, inner.orelse):
                        rendered = _raise_render(branch, numeric)
                        choices.extend(rendered if rendered else [_raise_sample(ast.unparse(branch), numeric)])
                elif isinstance(inner, ast.Constant) and isinstance(inner.value, str):
                    choices = [inner.value]
                else:
                    choices = [_raise_sample(ast.unparse(inner), numeric)]
                variants = [v + c for v in variants for c in choices]
        return variants
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _raise_render(node.left, numeric), _raise_render(node.right, numeric)
        if left and right:
            return [a + b for a in left for b in right]
    return None


def _raise_template(node) -> str:
    import ast

    if isinstance(node, ast.JoinedStr):
        return "".join(str(v.value) if isinstance(v, ast.Constant) else "{" + ast.unparse(v.value) + "}" for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return _raise_template(node.left) + _raise_template(node.right)
    return str(getattr(node, "value", ""))


def _scan_raise_literals(root=None) -> list[tuple[str, int, str, list[str]]]:
    """[(文件, 行号, 模板, 样本列表)]：``root``（默认本仓库的 src）下每个 raise …Error / HTTPException 的中文字面量。

    ``root`` 可以换成别的源码目录（比如插件目录），好让插件复用同一套扫描。"""

    import ast
    from pathlib import Path

    src = Path(root).resolve() if root is not None else Path(__file__).resolve().parents[1] / "src"
    rows = []
    for py in sorted(src.rglob("*.py")):
        if "static" in py.parts:
            continue
        tree = ast.parse(py.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            fn = node.func
            name = fn.id if isinstance(fn, ast.Name) else (fn.attr if isinstance(fn, ast.Attribute) else "")
            if not (name.endswith("Error") or name in _RAISE_NAMES):
                continue
            target = None
            if name == "HTTPException":
                target = node.args[1] if len(node.args) >= 2 else None
                for kw in node.keywords:
                    if kw.arg == "detail":
                        target = kw.value
            elif node.args:
                target = node.args[0]
            if target is None:
                continue
            samples = []
            for numeric in (False, True):
                rendered = _raise_render(target, numeric)
                if rendered:
                    samples.extend(rendered)
            if samples and any(_HAN.search(s) for s in samples):
                rows.append((py.relative_to(src.parent).as_posix(), node.lineno, _raise_template(target), samples))
    return rows


