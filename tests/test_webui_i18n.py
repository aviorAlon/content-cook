def test_saved_spec_errors_survive_an_english_round_trip(tmp_path, monkeypatch):
    """英文界面 GET 详情 → 编辑页把 spec 整份 PUT 回去（SetItems / ClipWrite / MusicGenerate 都这么存）：项目文件里
    落盘的中文失败原因不能被写成英文——中文是源文案，写回去以后中文界面也只剩英文、原文找不回来。
    页面显示用的派生行（items / attempts / first_frame）照样是英文。"""

    import json

    from clip import spec as clip_spec
    from imageset import spec as set_spec
    from music import spec as music_spec
    from webui import deps, tasks

    monkeypatch.setenv("STORYSTUDIO_HOME", str(tmp_path / "home"))
    monkeypatch.setenv("STORYSTUDIO_SETTINGS", str(tmp_path / "home" / "settings.json"))
    monkeypatch.setattr(deps, "PROJECT_ROOT", tmp_path)
    for module in ("sticker", "clip", "music"):
        (tmp_path / "content" / module).mkdir(parents=True)
    tasks._running.clear()
    i18n._compiled = None
    img = "image 模型未配置：image: 没选适配器（在「模型设置」里填好再生成）"
    vid = "video 模型未配置：video: 没选适配器（在「模型设置」里填好再生成）"
    mus = "music 模型未配置：music: 没选适配器（在「模型设置」里填好再生成）"

    def attempt(error: str) -> dict:
        return {"file": "x-1.bin", "created_at": 1.0, "model": "@x", "request_hash": "h", "task_id": None, "error": error}

    def plant(path, mutate) -> None:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        mutate(data)
        path.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")

    def disk(path) -> dict:
        return json.loads(path.read_text(encoding="utf-8-sig"))

    def round_trip(url: str) -> dict:
        shown = client.get(url, headers=_EN).json()
        body = {k: v for k, v in shown["spec"].items() if k not in ("output_root", "project_root")}
        r = client.put(url, json=body, headers=_EN)
