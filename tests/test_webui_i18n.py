    row = shown["items"][0]
    assert (row.get("error") or row.get("last_error") or "").startswith("image model not configured"), row
    assert row["attempts"][0]["error"].startswith("image model not configured")
    saved = disk(path)["items"][0]
    assert saved["error"] == img and saved["attempts"][0]["error"] == img

    # 片子：attempts[].error / first_frame.error
    r = client.post("/api/clip", json={"title": "往返片子", "style_anchor": "写实"})
    assert r.status_code == 200, r.text
    cid = r.json()["id"]
    path = clip_spec.clip_path(tmp_path, cid)

    def fail_clip(data: dict) -> None:
        data["attempts"] = [attempt(vid)]
        data["first_frame"]["error"] = img

    plant(path, fail_clip)
